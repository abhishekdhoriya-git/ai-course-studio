export function prepareFixture(store: StudioStore, workspaceRoot: string): FixturePlan {
  const existing = store.latestArtifact(FIXTURE_MANIFEST_ID);
  if (existing && store.isCurrent(existing)) {
    const plan = fixturePlanSchema.parse(artifactSchemas["workflow-report"].parse(existing.content).data["fixturePlan"]);
    return updateFixtureTemplate(store, workspaceRoot, plan);
  }
  if (existing) {
    const plan = fixturePlanSchema.parse(artifactSchemas["workflow-report"].parse(existing.content).data["fixturePlan"]);
    return store.atomic(() => updateFixtureTemplate(store, workspaceRoot, rebuildFixtureReview(store, plan)));
  }
  const brief = store.saveArtifact({
    id: "fixture:brief", kind: "course-brief",
    content: {
      title: "Engineering fixture: from brief to reviewed lesson",
      niche: "Engineering fixture only; the real pilot subject remains undecided",
      audience: "Studio implementers testing the pipeline; not a selected pilot audience",
      language: "en-US (fixture only)", prerequisites: [],
      objectives: ["Observe version-aware gates, local rendering, selective invalidation and four-item skill routing."],
    },
  });
  const evidence = store.saveArtifact({
    id: "fixture:evidence", kind: "evidence",
    content: {
      sources: [{
        url: "https://docs.github.com/en/copilot/concepts/customizations/agent-skills",
        retrievedAt: new Date().toISOString(), title: "GitHub Copilot: Agent skills",
        supports: ["Repository-local .github/skills packages are a supported discovery location."],
        uncertainty: "This fixture exercises the studio's local adapter, not automatic Copilot SDK orchestration.",
        rights: "Public documentation used as a factual reference; no protected assets copied.",
      }],
      claims: [{
        claim: "Copilot supports project skill packages in .github/skills.",
        sourceUrls: ["https://docs.github.com/en/copilot/concepts/customizations/agent-skills"],
      }],
      accessGaps: ["No pilot brief, trend/market research, owner reference videos, provider choice, identity recordings or budget have been supplied."],
    },
  });
  const curriculum = store.saveArtifact({
    id: "fixture:curriculum", kind: "curriculum",
    content: {
      title: "Engineering fixture, not an approved real course", brief, evidence,
      lessons: [{ id: "fixture:lesson", title: "From brief to reviewed lesson", objective: "Observe the local studio contracts.", prerequisites: [] }],
    },
  });
  const lesson = store.saveArtifact({
    id: "fixture:lesson", kind: "lesson",
    content: {
      courseId: "fixture:course", videoId: FIXTURE_VIDEO_ID, title: "From brief to reviewed lesson",
      objective: "Engineering fixture: demonstrate approvals, rendering and reusable scene reviews.", curriculum,
    },
  });
  const poster = savePoster(store, workspaceRoot);
  const specification = store.saveArtifact({
    id: "fixture:style-spec", kind: "style-spec",
    content: {
      origin: "original", observations: [], authorizedReferences: [],
      proposals: ["Original dark navy/teal teaching cards and simple vector diagrams; fixture-only style, not owner branding."],
      parameters: { background: "#101827", accent: "#68e8c5", font: "Arial", captionSafeAreaPx: 96 },
    },
  });
  const styleSample = store.saveArtifact({
    id: "fixture:style-sample", kind: "style-sample",
    content: { asset: poster, fixture: true, notes: "Original still style sample. Approve only for this engineering fixture; no reference analysis or cloned presenter is implied." },
    dependencies: [specification],
  });
  const template = fixtureTemplate(workspaceRoot);
  const templateRef = saveTemplate(store, template);
  const style = store.saveArtifact({
    id: "fixture:style", kind: "style-pack",
    content: {
      specification, sample: styleSample, templateVersion: FIXTURE_TEMPLATE_VERSION,
      parameters: { background: "#101827", accent: "#68e8c5", font: "Arial", captionSafeAreaPx: 96, templateHash: template.sourceHash },
    },
    dependencies: [templateRef],
  });
  const scenes = fixtureSceneTemplates.map((draft) => store.saveArtifact({
    id: `fixture:scene:${draft.sceneId}`, kind: "scene",
    content: { ...draft, videoId: FIXTURE_VIDEO_ID, assets: [], activities: ["produce-fixture-scene", "review-scene"] },
    dependencies: [lesson, evidence],
  }));
  const storyboard = store.saveArtifact({
    id: "fixture:storyboard", kind: "script-storyboard",
    content: { lesson, evidence, scenes: scenes.map((ref) => artifactSchemas.scene.parse(store.getArtifact(ref).content)) },
    dependencies: scenes,
  });
  const plan = fixturePlanSchema.parse({
    fixture: true, version: "1.0.0", videoId: FIXTURE_VIDEO_ID, title: "From brief to reviewed lesson",
    disclosure: "ENGINEERING FIXTURE / NON-CLONED PRESENTER & VOICE",
    width: 1280, height: 720, fps: 24, curriculum, lesson, storyboard, style, styleSample, scenes, poster,
  });
  saveFixturePlan(store, plan);
  return plan;
}

function saveTemplate(store: StudioStore, template: FixtureTemplate): ArtifactRef {
  return store.saveArtifact({
    id: FIXTURE_TEMPLATE_ID, kind: "workflow-report",
    content: {
      summary: "Installed local animation template and media recipe; content review is a separate exact-version decision.",
      data: { template: jsonSchema.parse(template) },
    },
  });
}

export function fixtureNeedsTemplateUpdate(store: StudioStore, root: string, plan: FixturePlan): boolean {
  const style = artifactSchemas["style-pack"].parse(store.getArtifact(plan.style).content);
  const template = fixtureTemplate(root);
  const record = store.latestArtifact(FIXTURE_TEMPLATE_ID);
  return !record || !store.isCurrent(record) || style.templateVersion !== template.version
    || style.parameters["templateHash"] !== template.sourceHash;
}

function updateFixtureTemplate(store: StudioStore, root: string, plan: FixturePlan): FixturePlan {
  if (!fixtureNeedsTemplateUpdate(store, root, plan)) return plan;
  return store.atomic(() => {
    const previous = store.getArtifact<"style-pack">(plan.style);
    const template = fixtureTemplate(root);
    const templateRef = saveTemplate(store, template);
    const style = store.saveArtifact({
      id: plan.style.id, kind: "style-pack",
      content: {
        ...previous.content, templateVersion: template.version,
        parameters: { ...previous.content.parameters, templateHash: template.sourceHash },
      },
      dependencies: [...previous.dependencies.filter((ref) => ref.id !== FIXTURE_TEMPLATE_ID), templateRef],
    });
    const next = { ...plan, style };
    saveFixturePlan(store, next);
    return next;
  });
}

export function currentFixture(store: StudioStore): FixturePlan | undefined {
  const artifact = store.latestArtifact(FIXTURE_MANIFEST_ID);
  return artifact && store.isCurrent(artifact)
    ? fixturePlanSchema.parse(artifactSchemas["workflow-report"].parse(artifact.content).data["fixturePlan"])
    : undefined;
}

export function lastFixtureForReview(store: StudioStore): FixturePlan | undefined {
  const artifact = store.latestArtifact(FIXTURE_MANIFEST_ID);
  return artifact ? fixturePlanSchema.parse(artifactSchemas["workflow-report"].parse(artifact.content).data["fixturePlan"]) : undefined;
}

function rebuildFixtureReview(store: StudioStore, previousPlan: FixturePlan): FixturePlan {
  const curriculumRecord = store.latestArtifact(previousPlan.curriculum.id);
  const lessonRecord = store.latestArtifact(previousPlan.lesson.id);
  const storyboardRecord = store.latestArtifact(previousPlan.storyboard.id);
  const styleRecord = store.latestArtifact(previousPlan.style.id);
  const sampleRecord = store.latestArtifact(previousPlan.styleSample.id);
  const posterRecord = store.latestArtifact(previousPlan.poster.id);
  if (!curriculumRecord || !lessonRecord || !storyboardRecord || !styleRecord || !sampleRecord || !posterRecord) {
    throw new MissingInputError("FIXTURE_INPUT_MISSING", "Keep the edited inputs and supply the missing fixture review records before rebuilding.");
  }
  store.requireCurrent(curriculumRecord);
  store.requireCurrent(styleRecord);
  store.requireCurrent(sampleRecord);
  store.requireCurrent(posterRecord);
  const curriculum = artifactSchemas.curriculum.parse(curriculumRecord.content);
  const previousCurriculum = artifactSchemas.curriculum.parse(store.getArtifact(previousPlan.curriculum).content);
  if (canonicalJson({ ...curriculum, title: "" }) !== canonicalJson({ ...previousCurriculum, title: "" })) {
    throw new MissingInputError("CURRICULUM_REAUTHORING_REQUIRED",
      "The curriculum's lessons, sources or prerequisites changed. Your edit is preserved; supply a consistent authored lesson/storyboard through Course planning instead of silently reusing the engineering fixture.");
  }
  const lessonContent = artifactSchemas.lesson.parse(lessonRecord.content);
  if (lessonContent.curriculum.id !== curriculumRecord.id || lessonContent.videoId !== previousPlan.videoId) {
    throw new MissingInputError("FIXTURE_LESSON_CONFLICT", "The lesson belongs to a different course/video. Resolve that authored input before rebuilding fixture review drafts.");
  }
  const sceneRecords = previousPlan.scenes.map((ref) => {
    const record = store.latestArtifact(ref.id);
    if (!record) throw new MissingInputError("FIXTURE_SCENE_MISSING", `Supply the edited scene record: ${ref.id}`);
    return record;
  });
  const scenes = sceneRecords.map((record) => artifactSchemas.scene.parse(record.content));
  const storyboardContent = artifactSchemas["script-storyboard"].parse(storyboardRecord.content);
  if (canonicalJson(scenes) !== canonicalJson(storyboardContent.scenes)) {
    throw new MissingInputError("FIXTURE_STORYBOARD_CONFLICT",
      "The storyboard and individual scene scripts differ. Your edits are preserved; reconcile those authored scripts before rebuilding review drafts.");
  }
  const toRef = ({ id, version, hash }: ArtifactRef): ArtifactRef => ({ id, version, hash });
  const replacements = new Map<string, ArtifactRef>([[curriculumRecord.id, toRef(curriculumRecord)]]);
  const rebind = (references: ArtifactRef[]) => references.map((ref) => replacements.get(ref.id) ?? ref);
  const lesson = store.saveArtifact({
    id: lessonRecord.id, kind: "lesson", content: { ...lessonContent, curriculum: toRef(curriculumRecord) },
    dependencies: rebind(lessonRecord.dependencies),
  });
  replacements.set(lesson.id, lesson);
  const sceneRefs = sceneRecords.map((record, index) => {
    const scene = store.saveArtifact({
      id: record.id, kind: "scene", content: scenes[index]!, dependencies: rebind(record.dependencies),
    });
    replacements.set(scene.id, scene);
    return scene;
  });
  const storyboard = store.saveArtifact({
    id: storyboardRecord.id, kind: "script-storyboard",
    content: { ...storyboardContent, lesson, scenes },
    dependencies: rebind(storyboardRecord.dependencies),
  });
  const plan = {
    ...previousPlan, title: lessonContent.title, curriculum: toRef(curriculumRecord), lesson, scenes: sceneRefs, storyboard,
    style: toRef(styleRecord), styleSample: toRef(sampleRecord), poster: toRef(posterRecord),
  };
  saveFixturePlan(store, plan);
  return plan;
}

export function saveFixturePlan(store: StudioStore, plan: FixturePlan): ArtifactRef {
  return store.saveArtifact({
    id: FIXTURE_MANIFEST_ID, kind: "workflow-report",
    content: {
      summary: "Explicit engineering fixture. This is not a pilot, digital clone or finished lesson.",
      references: [plan.curriculum, plan.lesson, plan.storyboard, plan.style, plan.styleSample, ...plan.scenes, plan.poster],
      data: { fixturePlan: jsonSchema.parse(plan) },
    },
  });
}

export function fixtureGates(store: StudioStore, plan: FixturePlan): { ref: ArtifactRef; gate: ApprovalGate; approved: boolean }[] {
  const gates: { ref: ArtifactRef; gate: ApprovalGate }[] = [
    { ref: plan.curriculum, gate: "curriculum" }, { ref: plan.styleSample, gate: "style" },
    { ref: plan.style, gate: "style" }, { ref: plan.lesson, gate: "lesson" },
    { ref: plan.storyboard, gate: "script-storyboard" },
  ];
  return gates.map((item) => ({ ...item, approved: store.isApproved(item.ref, item.gate) }));
}

export function requireFixtureGates(store: StudioStore, plan: FixturePlan): void {
  const missing = fixtureGates(store, plan).find((gate) => !gate.approved);
  if (missing) throw new MissingInputError("APPROVAL_REQUIRED", `Approve ${missing.ref.id}@${missing.ref.version} at ${missing.gate} before generating fixture audio or media.`);
}

export function refreshFixtureScene(store: StudioStore, updated: ArtifactRef): void {
  const previous = store.latestArtifact(FIXTURE_MANIFEST_ID);
  if (!previous || !updated.id.startsWith("fixture:scene:")) return;
  const oldPlan = fixturePlanSchema.parse(artifactSchemas["workflow-report"].parse(previous.content).data["fixturePlan"]);
  const scenes = oldPlan.scenes.map((ref) => ref.id === updated.id ? updated : ref);
  const oldStoryboard = artifactSchemas["script-storyboard"].parse(store.getArtifact(oldPlan.storyboard).content);
  const storyboard = store.saveArtifact({
    id: oldPlan.storyboard.id, kind: "script-storyboard",
    content: { ...oldStoryboard, scenes: scenes.map((ref) => artifactSchemas.scene.parse(store.requireCurrent(ref).content)) },
    dependencies: scenes,
  });
  saveFixturePlan(store, { ...oldPlan, scenes, storyboard });
}
